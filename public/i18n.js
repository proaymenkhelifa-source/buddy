// =============================================================
// LA LANGUE EN COURS
// Dans la page : la langue choisie. Sur le serveur : toujours le français,
// sauf pendant un withLang("en", …) (comme withTimeZone pour les fuseaux).
// =============================================================
let currentLang = "fr";

export const getLang = () => currentLang;
export const setLang = (lang) => { currentLang = lang in LANGUAGES ? lang : "fr"; };
export const locale = (lang = currentLang) => LOCALES[lang] || LOCALES.fr;

export function withLang(lang, fn) {
  const previous = currentLang;
  currentLang = lang in LANGUAGES ? lang : "fr";
  try { return fn(); } finally { currentLang = previous; }
}

// Une langue "propre" : "en", "en-US", "EN" → "en" ; inconnue → null
export function cleanLang(value) {
  const base = String(value || "").slice(0, 2).toLowerCase();
  return base in LANGUAGES ? base : null;
}

// LA fonction de traduction : t("nav.home") → "Accueil" ou "Home"
export function t(key, vars = {}, lang = currentLang) {
  const entry = DICT[lang]?.[key] ?? DICT.fr[key];
  if (entry === undefined) return key; // phrase inconnue : on affiche son nom (facile à repérer)
  if (typeof entry === "function") return entry(vars);
  return entry.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
}

// Les jours de la semaine (n : 1 = lundi … 7 = dimanche)
export const dayShort = (n, lang = currentLang) => (DAYS[lang] || DAYS.fr).short[n - 1];
export const dayLong = (n, lang = currentLang) => (DAYS[lang] || DAYS.fr).long[n - 1];
export const dayInitials = (lang = currentLang) => (DAYS[lang] || DAYS.fr).initials;
